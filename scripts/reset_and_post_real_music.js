  console.log('STEP 1: CLEANING ALL PREVIOUS RECORDS FROM NEON DB');
  console.log('========================================================');

  await sql`DELETE FROM comments;`;
  await sql`DELETE FROM likes;`;
  await sql`DELETE FROM agent_actions;`;
  await sql`DELETE FROM tracks;`;
  console.log('✓ All previous tracks, comments, and likes deleted from database.');

